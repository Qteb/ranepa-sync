        init(address: String, outline: [(Double, Double)]) {
            self.address = address
            self.outline = outline.map { CLLocationCoordinate2D(latitude: $0.0, longitude: $0.1) }
        }

        var center: CLLocationCoordinate2D {
            let n = Double(outline.count)
            return CLLocationCoordinate2D(latitude: outline.map(\.latitude).reduce(0, +) / n,
                                          longitude: outline.map(\.longitude).reduce(0, +) / n)
        }
    }

